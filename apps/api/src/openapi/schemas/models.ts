import { z } from '@hono/zod-openapi';
import { chatCompletionRequestSchema } from '@morphic/shared/types';

/**
 * Standard OpenAI-compatible Model object schema returned by /v1/models and /v1/models/:id.
 */
export const ModelObjectSchema = z
  .object({
    id: z.string().openapi({
      description: 'Public unique identifier of the model',
      example: 'morphic/deepseek-v4',
    }),
    object: z.literal('model').openapi({
      description: 'Object type identifier, always model',
      example: 'model',
    }),
    created: z.number().openapi({
      description: 'Unix timestamp representing creation time',
      example: 0,
    }),
    owned_by: z.string().openapi({
      description: 'Organization owning or serving the model gateway',
      example: 'morphic',
    }),
    display_name: z.string().openapi({
      description: 'Human-readable model name for display',
      example: 'DeepSeek V4',
    }),
    context_length: z.number().openapi({
      description: 'Maximum supported context window size in tokens',
      example: 128000,
    }),
    capabilities: z.array(z.string()).openapi({
      description: 'List of features supported by the model (e.g. tools, vision, reasoning)',
      example: ['tools', 'vision'],
    }),
    status: z.enum(['active', 'deprecated']).openapi({
      description: 'Lifecycle status of the model',
      example: 'active',
    }),
    replacement_model_alias: z.string().nullable().openapi({
      description: 'Recommended model ID to use if this model is deprecated',
      example: null,
    }),
  })
  .openapi('ModelObject');

/**
 * List wrapper for models endpoint matching OpenAI GET /v1/models response.
 */
export const ModelListResponseSchema = z
  .object({
    object: z.literal('list').openapi({
      description: 'Object type identifier, always list',
      example: 'list',
    }),
    data: z.array(ModelObjectSchema).openapi({
      description: 'Array of accessible model objects',
    }),
  })
  .openapi('ModelListResponse');

/**
 * Chat completion choice message item.
 */
export const ChatCompletionMessageSchema = z
  .object({
    role: z.enum(['system', 'user', 'assistant', 'tool', 'developer']).openapi({
      description: 'Role of the message author',
      example: 'assistant',
    }),
    content: z.string().nullable().openapi({
      description: 'The contents of the message',
      example: 'Hello! How can I help you today?',
    }),
    tool_calls: z.array(z.unknown()).optional().openapi({
      description: 'Tool calls generated by the model, if any',
    }),
    refusal: z.string().nullable().optional().openapi({
      description: 'Refusal message generated by the model, if any',
      example: null,
    }),
  })
  .openapi('ChatCompletionMessage');

/**
 * Individual completion choice returned in non-streaming responses.
 */
export const ChatCompletionChoiceSchema = z
  .object({
    index: z.number().openapi({
      description: 'Index of the choice in the list',
      example: 0,
    }),
    message: ChatCompletionMessageSchema,
    finish_reason: z.string().nullable().openapi({
      description: 'Reason the model stopped generating tokens',
      example: 'stop',
    }),
  })
  .openapi('ChatCompletionChoice');

/**
 * Token usage statistics for the completion request.
 */
export const ChatCompletionUsageSchema = z
  .object({
    prompt_tokens: z.number().openapi({
      description: 'Number of tokens in the prompt',
      example: 24,
    }),
    completion_tokens: z.number().openapi({
      description: 'Number of tokens generated in the completion',
      example: 88,
    }),
    total_tokens: z.number().openapi({
      description: 'Total number of tokens used in request and response',
      example: 112,
    }),
  })
  .openapi('ChatCompletionUsage');

/**
 * Full OpenAI-compatible chat completion response object for non-streaming calls.
 */
export const ChatCompletionResponseSchema = z
  .object({
    id: z.string().openapi({
      description: 'Unique identifier for the chat completion',
      example: 'chatcmpl-9x1a2b3c4d5e',
    }),
    object: z.literal('chat.completion').openapi({
      description: 'Object type identifier, always chat.completion',
      example: 'chat.completion',
    }),
    created: z.number().openapi({
      description: 'Unix timestamp in seconds when the completion was created',
      example: 1718000000,
    }),
    model: z.string().openapi({
      description: 'Model identifier used to generate the response',
      example: 'morphic/deepseek-v4',
    }),
    choices: z.array(ChatCompletionChoiceSchema).openapi({
      description: 'List of completion choices generated by the model',
    }),
    usage: ChatCompletionUsageSchema.optional(),
  })
  .openapi('ChatCompletionResponse');

/**
 * OpenAPI-wrapped ChatCompletionRequestSchema from @morphic/shared/types.
 */
export const ChatCompletionRequestSchema = chatCompletionRequestSchema;
